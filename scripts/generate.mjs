#!/usr/bin/env node
/**
 * Regenerates the typed entry points in `src/lib/<name>/index.ts`.
 *
 * The Lottie JSON files themselves are NOT copied into this package: they are imported
 * from the official `react-useanimations` package (published by the useAnimations
 * authors), so this module never redistributes their artwork.
 *
 * When upstream adds a new icon:
 *   1. `bun add react-useanimations@latest`
 *   2. Add `"newIcon": "<EFFECT>"` to `scripts/effects.json`
 *   3. `bun run generate`
 */
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const libDir = path.join(root, 'src', 'lib');
const require = createRequire(import.meta.url);
const upstreamLib = path.join(path.dirname(require.resolve('react-useanimations/package.json')), 'lib');
const effects = JSON.parse(fs.readFileSync(path.join(root, 'scripts', 'effects.json'), 'utf8'));

const VALID_EFFECTS = new Set([
  'CLICK_PLAY_AND_BACKWARDS',
  'HOVER_PLAY_AND_STOP',
  'HOVER_PLAY_AND_BACKWARDS',
  'CLICK_PLAY',
  'LOOP_PLAY',
  'CLICK_PLAY_AND_SEGMENTS',
]);

const names = fs
  .readdirSync(upstreamLib, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

fs.rmSync(libDir, { recursive: true, force: true });
for (const name of names) {
  let effect = effects[name];
  if (!VALID_EFFECTS.has(effect)) {
    console.warn(`⚠ "${name}" has no effect in scripts/effects.json, defaulting to CLICK_PLAY`);
    effect = 'CLICK_PLAY';
  }
  fs.mkdirSync(path.join(libDir, name), { recursive: true });
  fs.writeFileSync(
    path.join(libDir, name, 'index.ts'),
    `import source from 'react-useanimations/lib/${name}';

import type { Animation } from '../../types';

/** useAnimations "${name}" icon (© useanimations.com, CC BY 4.0). */
const ${name}: Animation = {
  animationKey: '${name}',
  animationData: source.animationData,
  effect: '${effect}',
};

export default ${name};
`
  );
}

const header = '// AUTO-GENERATED by scripts/generate.mjs — do not edit by hand.\n';

fs.writeFileSync(
  path.join(root, 'src', 'keys.ts'),
  `${header}export type AnimationKey =
${names.map((n) => `  | '${n}'`).join('\n')};

export const animationKeys: readonly AnimationKey[] = [
${names.map((n) => `  '${n}',`).join('\n')}
];
`
);

fs.writeFileSync(
  path.join(root, 'src', 'all.ts'),
  `${header}// ⚠️ Importing this file bundles EVERY animation (~1 MB). Prefer per-icon imports:
//    import heart from 'expo-useanimations/lib/heart';
import type { Animation } from './types';
import type { AnimationKey } from './keys';
${names.map((n) => `import ${n} from './lib/${n}';`).join('\n')}

const animations: Record<AnimationKey, Animation> = {
${names.map((n) => `  ${n},`).join('\n')}
};

export default animations;
`
);

console.log(`Generated ${names.length} animations.`);
